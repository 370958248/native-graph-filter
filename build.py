from pathlib import Path
import json, re, struct, zipfile
ROOT=Path(__file__).resolve().parent
FILES=['plugin.json','index.js','index.css','filter.js','bridge.js','ui.js','README.md','LICENSE','icon.svg','icon.png','preview.png']
def build(output):
    manifest=json.loads((ROOT/'plugin.json').read_text(encoding='utf-8'))
    assert manifest['name']=='native-graph-filter'
    assert manifest['url']=='https://github.com/370958248/native-graph-filter'
    assert re.fullmatch(r'\d+\.\d+\.\d+',manifest['version'])
    for key in ['displayName','description','readme']:
        assert manifest[key].get('default') and all('_' not in locale for locale in manifest[key])
    # SiYuan exposes its SDK require, not Node's relative-module loader.
    factories=[]
    for name in ['filter','bridge','ui','main']:
        source=(ROOT/(name+'.js')).read_text(encoding='utf-8')
        factories.append(json.dumps(name)+':function(module,exports,require){\n'+source+'\n}')
    bundle='// Generated by build.py from main.js, filter.js, bridge.js and ui.js.\n'
    bundle+='(function(externalRequire,rootModule){\nconst factories={'+',\n'.join(factories)+'};\n'
    bundle+='const cache={};function load(name){if(name==="siyuan")return externalRequire(name);name=name.replace(/^\\.\\//,"").replace(/\\.js$/,"");if(cache[name])return cache[name].exports;if(!factories[name])throw Error("Unknown module: "+name);const m={exports:{}};cache[name]=m;factories[name](m,m.exports,load);return m.exports;}rootModule.exports=load("main");\n})(require,module);\n'
    (ROOT/'index.js').write_text(bundle,encoding='utf-8',newline='\n')
    for name in FILES: assert (ROOT/name).is_file(),name
    for name,expected,limit in [('icon.png',(160,160),64*1024),('preview.png',(1024,768),512*1024)]:
        data=(ROOT/name).read_bytes();assert data[:8]==b'\x89PNG\r\n\x1a\n' and struct.unpack('>II',data[16:24])==expected and len(data)<=limit,name
    for name in FILES:
        if Path(name).suffix in ['.js','.json','.css','.md']:
            text=(ROOT/name).read_text(encoding='utf-8')
            assert not re.search(r'\b\d{14}-[a-z0-9]{7}\b',text),name
            assert not re.search(r'(?i)\b[A-Z]:[\\/]',text),name
    with zipfile.ZipFile(output,'w',compression=zipfile.ZIP_DEFLATED) as z:
        for name in sorted(FILES):
            info=zipfile.ZipInfo(name,(2026,1,1,0,0,0));info.compress_type=zipfile.ZIP_DEFLATED;info.external_attr=0o644<<16
            z.writestr(info,(ROOT/name).read_bytes())
    with zipfile.ZipFile(output) as z: assert z.testzip() is None and len(z.namelist())==len(FILES)
    print(json.dumps({'version':manifest['version'],'files':len(FILES),'bytes':Path(output).stat().st_size}))
if __name__=='__main__':
    import argparse
    p=argparse.ArgumentParser();p.add_argument('--output',type=Path,default=ROOT/'package.zip');build(p.parse_args().output)
